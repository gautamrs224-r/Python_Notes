# If_else, we use to check the condition of something and execute a block of code if the condition is true.

# Syntax:
user = int(input("Enter your age here :"))
if( user >= 18):
    print("You are the above the Age. You can drive.")
else:
    print("You are the below the Age. You can't drive.")

# Performing operations using if_else

num1 = int(input("Enter first number: "))
num2 = int(input("Enter second number: "))

if num1 > num2:
    print(num1, "is greater than", num2)
else:
    print(num2, "is greater than", num1)

