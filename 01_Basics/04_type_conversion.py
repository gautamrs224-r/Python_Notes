# Type conversion or Tpyecasting:
# Type conversion is the process of converting one data type to another. In Python, you can use the following functions to perform type conversion:
# 1. int() - converts a value to an integer
# 2. float() - converts a value to a floating-point number
# 3. str() - converts a value to a string
# 4. bool() - converts a value to a boolean

# Example of type conversion
x = 10
y = float(x)
print("Type of variable y is:", type(y)) # Output: Type of variable y is: <class 'float'>

z = str(x)
print("Type of variable z is:", type(z)) # Output: Type of variable z is: <class 'str'>

a = bool(x)
print("Type of variable a is:", type(a)) # Output: Type of variable a is: <class 'bool'>

b = int(y)
print("Type of variable b is:", type(b)) # Output: Type of variable b is: <class 'int'>

c = float(z)
print("Type of variable c is:", type(c)) # Output: Type of variable c is: <class 'float'>

d = bool(z)
print("Type of variable d is:", type(d)) # Output: Type of variable d is: <class 'bool'>